use base64::Engine as _;

/// A valid zlib stream for a single RGBA pixel.
const VALID_ZLIB: &[u8] = &[
    0x78, 0x9c, 0x63, 0x64, 0x62, 0x66, 0x01, 0x00, 0x00, 0x18, 0x00, 0x0b,
];

